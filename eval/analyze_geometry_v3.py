#!/usr/bin/env python3
"""Geometry-only reproduction of the primary ladder (revision v2: same-defect study removed).

This rebuilds GEOMETRIC_LADDER_V3.json from the top-3 finding population ALONE. It reads no reviewer
sheet, no blinding key, and no lock. Every rung of the ladder is a property of the vendor diff, so the
geometry is fully independent of any adjudication. The pooled top-3 population is the rank<=3 slice of
FINDING_POPULATION_V3.jsonl (710 findings on the matched-100 sample); the geometric fields
(in_patched_file, same_callable, exact_line, proximity, same_hunk, class_match) are copied straight
from the population records, which is exactly the geometry analyze_v3 used to join with the labels.

    python3 -m eval.analyze_geometry_v3            # rewrites + verifies GEOMETRIC_LADDER_V3.json
    python3 -m eval.analyze_geometry_v3 --check    # verify only, do not rewrite

The point of a separate script is that the manuscript's primary numbers no longer pass through the
label sheets at all: the geometry is derivable from the released finding population by itself.
"""
from __future__ import annotations
import os, sys, json, time, platform, argparse, hashlib
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from eval import adjudication_v3_common as C
from eval import analyze_v3 as A            # reuse the vetted geometry + bootstrap, never its main()

OUT_DIR = A.OUT_DIR
TOPK = 3
LADDER = os.path.join(OUT_DIR, "GEOMETRIC_LADDER_V3.json")


def geom_units_from_population():
    """The rank<=TOPK slice of the finding population, geometry only, no labels.

    Failure policy: this ladder is a rate over FINDINGS, so it uses the "kept" arm. Contract
    v1 s4 rule 3 makes a non-converged record a miss "over the full RECORD denominator", and
    that is where it is applied: the paired family, the equal-budget matrix and the
    full-corpus tables, where a record a tool failed on is a 0 for every tool alike.

    Applying it here instead would not be symmetric. A baseline that times out emits nothing,
    so its failed records never enter a per-finding denominator and cost it nothing (semgrep
    failed 3 records and contributes 0 findings from them, progpilot 46 -> 0, wpt 23 -> 0).
    WISP's non-converged records DO emit: 22 records, 66 top-3 findings. Charging only the
    tool whose failure mode is visible would penalise WISP alone and move the ladder by more
    than the effect being measured. The rule-3 arm is reported as a sensitivity instead
    (eval/ladder_failure_policy_v3.py).
    """
    pop = C.load_population(topk=TOPK, failure_policy="kept")
    units = []
    for g in pop:
        d = g["distance_to_nearest_changed_line"]
        within = lambda n: (d is not None and d <= n)
        units.append({
            "slug": g["slug"], "cve": g["cve"], "tool": g["tool"], "rank": g["rank"],
            "finding_uid": g["finding_uid"],
            "in_patched_file": bool(g["in_patched_file"]),
            "same_callable_as_change": bool(g["same_callable_as_change"]),
            "on_exact_changed_line": bool(g["on_exact_changed_line"]),
            "within_2_changed_lines": bool(within(2)),
            "within_5_changed_lines": bool(g["within_5_changed_lines"]),
            "within_10_changed_lines": bool(within(10)),
            "same_diff_hunk": bool(g["same_diff_hunk"]),
            "class_match": bool(g["class_match"]),
        })
    return units


def geometry_latex_macros(geom):
    """The primary-macro file the manuscript \\input's. Geometry only: no same-defect, no kappa."""
    def mac(name, val):
        return f"\\newcommand{{\\{name}}}{{{val}}}"
    L = ["% Auto-generated by eval/analyze_geometry_v3.py. Do not edit by hand.",
         "% Geometric ladder is the primary result. The defect-level study is reported separately,\n"
         "% from human labels, and is not an input to any number in this file."]
    for tool in ("wisp", "semgrep", "wpt"):
        t = tool.capitalize()
        pt = geom["per_tool"].get(tool, {})
        if pt.get("n_findings"):
            L.append(mac(f"{t}InPatchedFile", f"{pt['in_patched_file']['rate']:.3f}"))
            L.append(mac(f"{t}ExactChangedLine", f"{pt['on_exact_changed_line']['rate']:.3f}"))
            L.append(mac(f"{t}SameDiffHunk", f"{pt['same_diff_hunk']['rate']:.3f}"))
            L.append(mac(f"{t}ProxFive", f"{pt['within_5_changed_lines']['rate']:.3f}"))
            de = geom["primary_effect"][tool]["drop_to_exact_changed_line"]
            L.append(mac(f"{t}DropToExact", f"{de['diff']:.3f}"))
            L.append(mac(f"{t}DropToExactCILo", f"{de['ci95'][0]:.3f}"))
            L.append(mac(f"{t}DropToExactCIHi", f"{de['ci95'][1]:.3f}"))
    return "\n".join(L) + "\n"


def provenance(reps, pop_path):
    commit, dirty = A._git_commit()
    return {"schema_version": "analysis-v3-geometry", "script": "eval/analyze_geometry_v3.py",
            "script_git_commit": commit, "git_dirty": dirty,
            "input_hashes": {"population": A._sha256(pop_path), "ladder": A._sha256(C.LADDER)},
            "seed": A.SEED, "bootstrap_replicates": reps,
            "timestamp_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "python_version": platform.python_version(), "numpy_version": np.__version__,
            "config": {"tools": A.TOOLS, "topk": TOPK, "bootstrap_unit": "plugin_slug",
                       "source": "finding population only, no adjudication sheets"}}


def _strip(o, volatile):
    if isinstance(o, dict):
        return {k: _strip(v, volatile) for k, v in o.items() if k not in volatile}
    if isinstance(o, list):
        return [_strip(x, volatile) for x in o]
    return o


def _payload_fp(obj):
    volatile = {"timestamp_utc", "git_dirty", "script_git_commit", "python_version",
                "numpy_version", "schema_version", "script", "input_hashes", "artifact_kind", "config"}
    return hashlib.sha256(json.dumps(_strip(obj, volatile), sort_keys=True).encode()).hexdigest()[:16]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reps", type=int, default=10000)
    ap.add_argument("--check", action="store_true", help="verify against shipped, do not rewrite")
    a = ap.parse_args()

    units = geom_units_from_population()
    per_tool = {}
    for u in units:
        per_tool[u["tool"]] = per_tool.get(u["tool"], 0) + 1
    records_all = [tuple(k.split("|", 1)) for k in C.load_manifest_records()]
    n_records = len(records_all)

    print(f"geometry-only reproduction: {len(units)} top-{TOPK} findings "
          f"({', '.join(f'{t} {n}' for t, n in sorted(per_tool.items()))}) over {n_records} records, "
          f"no sheets read")
    geom = A.geometric_ladder(units, n_records, a.reps)
    prov = provenance(a.reps, C.POPULATION)
    out = A.stamped(prov, "geometric_ladder", geom)

    shipped = json.load(open(LADDER)) if os.path.isfile(LADDER) else None
    match = shipped is not None and _payload_fp(shipped) == _payload_fp(out)

    if not a.check:
        with open(LADDER, "w", encoding="utf-8") as fh:
            json.dump(out, fh, indent=1)
        with open(os.path.join(OUT_DIR, "LATEX_MACROS_V3.tex"), "w", encoding="utf-8") as fh:
            fh.write(geometry_latex_macros(geom))

    if shipped is None:
        print("no shipped ladder to compare; wrote fresh GEOMETRIC_LADDER_V3.json")
        return 0
    wisp = geom["per_tool"]["wisp"]
    print(f"  pooled patched_file={geom['pooled']['in_patched_file']['rate']} "
          f"exact_line={geom['pooled']['on_exact_changed_line']['rate']}; "
          f"WISP file={wisp['in_patched_file']['rate']} exact={wisp['on_exact_changed_line']['rate']}")
    if match:
        print("GEOMETRIC LADDER: reproduced from the finding population alone and MATCHES shipped.")
        return 0
    print("GEOMETRIC LADDER: MISMATCH against shipped payload.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
