#!/usr/bin/env python3
"""Emit the whole 39-comparison family as a main-text matrix, and check the emitted copy.

The reviewer's P1-1/P1-2 group says the main paper does not stand on its own, and lists what was
pushed into the supplement: the endpoint glossary, the two metric formulas, the corpus ladder, and
the family of 39 paired comparisons. The ladder and the formulas are back in the main text. The
family is the one left, and it is the expensive one: the supplement's `tab:clusterp` is 39 rows of
seven columns, and the journal counts every token in a table, so lifting it whole costs about 360
words against a limit with single digits of headroom.

The seven columns are not what makes the family answer the objection. The objection is that a
reader of the main text cannot see which comparisons the paper declared, or which of them survived
correction, without turning to the supplement. That is a 39-cell fact, and 39 cells fit: this emits
the same family as 13 endpoint rows by 3 baseline columns, each cell the Holm-adjusted p, bold when
it does not survive. Nothing is dropped and nothing is summarized. The discordant counts, the two
uncorrected p-values and the caption's methodology stay in the supplement, which the word limit does
not bind, and the main-text caption names that table.

Every cell is read from PAIRED_FAMILY_V3.json. No value is transcribed, which is the same rule
`PAIRED_FAMILY_TABLE.tex` carries at the top of itself, and `--check` re-derives the file on disk
from the JSON and exits non-zero on any drift, so the fragment cannot go stale silently while the
analysis moves under it.

    python3 -m eval.build_family_compact_v3
    python3 -m eval.build_family_compact_v3 --check
    python3 -m eval.build_family_compact_v3 --selftest
"""
from __future__ import annotations
import argparse, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from eval import adjudication_v3_common as C

SYS_ROOT = C.SYS_ROOT
SRC = os.path.join(SYS_ROOT, "revision-cns-v2", "out", "PAIRED_FAMILY_V3.json")
DEST = os.path.join(SYS_ROOT, "2026-07-07", "latex", "PAIRED_FAMILY_COMPACT.tex")

# The order the main text reads the ladder in: coarse first, then class-aware, then line
# granularity. It is the containment order of the endpoints, so a reader going down the table is
# tightening the target, which is the paper's whole argument.
ROW_ORDER = ["class",
             "pf@1", "pf@3", "pf@5", "pf@10",
             "cf@1", "cf@3", "cf@5", "cf@10",
             "exact@1", "exact@3", "exact@5", "exact@10"]
ROW_LABEL = {"class": "class emission",
             "pf@1": "patch-file@1", "pf@3": "patch-file@3",
             "pf@5": "patch-file@5", "pf@10": "patch-file@10",
             "cf@1": "class-and-file@1", "cf@3": "class-and-file@3",
             "cf@5": "class-and-file@5", "cf@10": "class-and-file@10",
             "exact@1": "exact line@1", "exact@3": "exact line@3",
             "exact@5": "exact line@5", "exact@10": "exact line@10"}
COL_ORDER = ["semgrep", "progpilot", "wpt"]
RULES_AFTER = {"class", "pf@10", "cf@10"}


def fmt_p(p: float) -> str:
    """Two significant figures, and scientific notation only where a decimal would be unreadable.

    Matches how PAIRED_FAMILY_TABLE.tex already prints the same quantity, so a reader comparing the
    two tables is not made to reconcile two renderings of one number.
    """
    if p >= 0.001:
        return f"{p:.4f}".rstrip("0").rstrip(".") if p < 1 else "1.0000"
    return f"{p:.1e}"


def render(doc: dict) -> str:
    comps = doc["comparisons"]
    lines = []
    for r in ROW_ORDER:
        cells = []
        for b in COL_ORDER:
            key = f"{r} vs {b}"
            if key not in comps:
                raise SystemExit(f"{SRC} has no comparison {key!r}; the family is not the "
                                 f"{len(ROW_ORDER)}x{len(COL_ORDER)} this table assumes")
            c = comps[key]
            s = fmt_p(float(c["p_holm_adjusted"]))
            cells.append(s if c["survives_holm"] else r"\textbf{%s}" % s)
        lines.append(f"{ROW_LABEL[r]} & " + " & ".join(cells) + r" \\")
        if r in RULES_AFTER:
            lines.append(r"\midrule")
    n = len(ROW_ORDER) * len(COL_ORDER)
    if n != doc["family"]["size"]:
        raise SystemExit(f"this table lays out {n} cells and the family declares "
                         f"{doc['family']['size']}. One of them is wrong and it is not this file's "
                         f"place to guess which.")
    head = ("% Auto-generated by eval/build_family_compact_v3.py from PAIRED_FAMILY_V3.json.\n"
            "% Every cell is a JSON pointer, not a transcription. Do not edit by hand.\n"
            "% Cell = Holm-adjusted p over the whole family. Bold = does not survive at alpha=0.05.\n")
    # \bottomrule lives INSIDE this fragment, exactly as PAIRED_FAMILY_TABLE.tex puts it, because
    # putting it in the parent after \input makes TeX read \noalign outside a row boundary and the
    # build dies with "Misplaced \noalign" and no PDF. Found by building, 2026-08-20.
    return head + "\n".join(lines) + "\n" + "\\bottomrule\n"


def _selftest() -> int:
    """The two ways this file could be wrong while still producing a table."""
    fails = []

    def want(cond, msg):
        if not cond:
            fails.append(msg)

    want(fmt_p(1.0) == "1.0000", f"1.0 printed as {fmt_p(1.0)!r}")
    want(fmt_p(0.2071) == "0.2071", f"0.2071 printed as {fmt_p(0.2071)!r}")
    want(fmt_p(0.0486) == "0.0486", f"0.0486 printed as {fmt_p(0.0486)!r}")
    want(fmt_p(3.1e-14) == "3.1e-14", f"3.1e-14 printed as {fmt_p(3.1e-14)!r}")

    # the layout must cover the declared family exactly once, with no key used twice
    keys = [f"{r} vs {b}" for r in ROW_ORDER for b in COL_ORDER]
    want(len(keys) == len(set(keys)) == 39, "the layout does not name 39 distinct comparisons")

    # a survivor must not be bolded and a non-survivor must be
    doc = {"comparisons": {k: {"p_holm_adjusted": 0.5, "survives_holm": (i % 2 == 0)}
                           for i, k in enumerate(keys)},
           "family": {"size": 39}}
    body = render(doc)
    want(body.count(r"\textbf{") == 19, f"bolded {body.count(chr(92)+'textbf{')} of the 19 non-survivors")

    # a family that is not 39 must be refused rather than silently laid out
    doc2 = {"comparisons": doc["comparisons"], "family": {"size": 40}}
    try:
        render(doc2)
        fails.append("a family declaring 40 was laid out as 39")
    except SystemExit:
        pass

    # a missing comparison must be refused, not rendered as a blank cell
    doc3 = {"comparisons": {k: v for k, v in doc["comparisons"].items() if k != keys[0]},
            "family": {"size": 39}}
    try:
        render(doc3)
        fails.append("a missing comparison was rendered rather than refused")
    except SystemExit:
        pass

    if fails:
        print("SELFTEST FAILED:")
        for f in fails:
            print("  - " + f)
        return 1
    print("SELFTEST OK: 39 distinct cells, non-survivors bolded, a wrong family size and a missing "
          "comparison both refused")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="re-derive from the JSON and fail if the file on disk differs")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--src", default=SRC)
    ap.add_argument("--dest", default=DEST)
    a = ap.parse_args()

    if a.selftest:
        return _selftest()

    body = render(json.load(open(a.src, encoding="utf-8")))
    if a.check:
        if not os.path.isfile(a.dest):
            print(f"  FAIL: {os.path.relpath(a.dest, SYS_ROOT)} does not exist")
            return 1
        on_disk = open(a.dest, encoding="utf-8").read()
        if on_disk != body:
            print(f"  FAIL: {os.path.relpath(a.dest, SYS_ROOT)} does not match "
                  f"{os.path.relpath(a.src, SYS_ROOT)}")
            for i, (x, y) in enumerate(zip(on_disk.splitlines(), body.splitlines()), 1):
                if x != y:
                    print(f"    line {i} on disk: {x}")
                    print(f"    line {i} derived: {y}")
            return 1
        print(f"  OK: {len(ROW_ORDER)}x{len(COL_ORDER)} = {len(ROW_ORDER)*len(COL_ORDER)} cells "
              f"match {os.path.relpath(a.src, SYS_ROOT)}")
        return 0

    open(a.dest, "w", encoding="utf-8").write(body)
    print("wrote " + os.path.relpath(a.dest, SYS_ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
