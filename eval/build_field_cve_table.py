#!/usr/bin/env python3
"""Emit the supplement table that names every CVE in the field-validation campaign.

The paper said 26 of the authors' reports became published CVEs and that 24 of them were
re-scanned, and it named none of them. A reader could not check that the advisories exist, that a
CNA credited them, or why two were left out. The identifiers were in the result file the whole
time, so the table is generated from it rather than written out by hand.

    python3 -m eval.build_field_cve_table
"""
from __future__ import annotations
import os, sys, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYS_ROOT = os.path.dirname(ROOT)
SRC = os.path.join(SYS_ROOT, "revision-cns-v2", "out", "FIELD_VALIDATION_V1.json")
OUT = os.path.join(SYS_ROOT, "2026-07-07", "latex", "FIELD_CVE_TABLE.tex")

CLS = {"xss": "XSS", "sqli": "SQLi", "rce": "RCE", "auth": "access control",
       "lfi": "LFI", "ssrf": "SSRF", "csrf": "CSRF", "deserial": "object injection",
       "upload": "upload", "other": "other"}


def esc(s):
    return str(s).replace("_", r"\_").replace("&", r"\&").replace("#", r"\#")


def cvelink(cve):
    """A CVE identifier that a reader can click through to the CVE Program record.

    Added 2026-08-26. An identifier printed as plain text asks the reader to retype it, and a
    24-row table asks that 24 times. The URL form is the one CVE.org itself publishes, so it does
    not depend on any mirror staying up. Both documents load hyperref, so \href resolves in each.
    The visible text stays the bare identifier, because the link must not change what the table
    says on paper.
    """
    return r"\href{https://www.cve.org/CVERecord?id=" + cve + "}{" + esc(cve) + "}"


def rank(v):
    """The cutoff at which the rung was first reached, or 'none' when it never was."""
    return "none" if v is None else f"$K{{=}}{v}$"


def main():
    d = json.load(open(SRC, encoding="utf-8"))
    recs = sorted(d["records"], key=lambda r: (not r["in_corpus"], r["cve"] or "", r["slug"]))
    lines = [
        "% Auto-generated by eval/build_field_cve_table.py. Do not edit by hand.",
        # 2026-08-26: this table sat 21.8pt past \textwidth and shipped that way, because the
        # build read every number in it and no warning about its width. The long cells are the
        # plugin slugs. tabcolsep is scoped by the table environment that \inputs this file.
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}llllccc@{}}",
        r"\toprule",
        r"CVE & Plugin & Class & Fixed in & In corpus & patch-file & class-and-file \\",
        r"\midrule",
    ]
    unrecorded = [r["slug"] for r in recs if not r["cve"]]
    for r in recs:
        lines.append(
            " & ".join([
                cvelink(r["cve"]) if r["cve"] else r"\emph{not recorded}",
                r"\code{" + esc(r["slug"]) + "}",
                CLS.get(r["cls"], r["cls"]),
                r"\code{" + esc(r["patched_version"]) + "}",
                "yes" if r["in_corpus"] else "no",
                rank(r["pf"]),
                rank(r["cf"]),
            ]) + r" \\"
        )
    lines.append(r"\midrule")
    # These rows are not published advisories. The JSON records them under not_scanned with the
    # reason, and reports_without_published_cve names the same plugins: support closed before a
    # fixed release existed, so there is no release pair to diff and no identifier to carry. The
    # old heading said "Published but not re-scanned", which asserted publication the data denies,
    # and it survived because it is a hardcoded string in this generator rather than a number any
    # macro guard reads.
    lines.append(r"\multicolumn{7}{@{}l@{}}{\emph{Reported, no published advisory, not re-scanned}} \\")
    for slug, why in sorted(d["not_scanned"].items()):
        lines.append(r"\multicolumn{7}{@{}l@{}}{\quad \code{" + esc(slug) + "}: "
                     + esc(why) + r"} \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")

    # 2026-08-26, second output. The author wanted the identifiers themselves in the MAIN text, not
    # only in the supplement, because a reader who cannot name the vulnerabilities cannot check that
    # the field campaign happened. Three columns only, and the rows are dealt into two side-by-side
    # blocks so the table costs half the page height for the same words. The manuscript is at its
    # 12000-word ceiling, so every column here was argued for: identifier, what it was found in, and
    # the release that fixed it. Class and the per-rung outcome stay in the supplement's wider table.
    def slugbreak(x):
        """A slug in \\texttt does not hyphenate, so a 41-character one overflows any column
        narrow enough to fit two blocks side by side. Hyphens are the natural break points and
        \\allowbreak takes no width, so the printed slug is unchanged."""
        return esc(x).replace("-", r"-\allowbreak ")

    named_recs = [r for r in recs if r["cve"]]
    half = (len(named_recs) + 1) // 2
    left, right = named_recs[:half], named_recs[half:]
    m = [
        "% Auto-generated by eval/build_field_cve_table.py from FIELD_COMPARISON_V1.json.",
        "% Compact main-text form. Do not edit by hand.",
        r"\begin{table*}[!t]",
        r"\centering\footnotesize",
        r"\caption{The " + str(len(named_recs)) + r" published CVEs behind the field validation, "
        # A \ref into the OTHER document does not resolve, and a hand-typed number goes stale the
        # day a table is inserted before it, so the supplement is addressed by NAME. That is the
        # rule check_cross_document_pointers.py enforces.
        r"each fixed by the vendor in the release named. The supplement's section "
        r"\emph{The same records, scored for all four scanners} scores every one for all "
        r"four tools.}",
        r"\label{tab:fieldcve}",
        r"\setlength{\tabcolsep}{4pt}",
        # The plugin column has to WRAP. colissimo-shipping-methods-for-woocommerce is 41 characters
        # and an l column cannot break it, which put this table 57pt past \textwidth on its first
        # build. Fixed width plus raggedright, because a justified 115pt column of slugs is worse.
        r"\begin{tabular}{@{}l>{\raggedright\arraybackslash}p{112pt}l"
        r"@{\hspace{1.2em}}l>{\raggedright\arraybackslash}p{112pt}l@{}}",
        r"\toprule",
        r"CVE & Plugin & Fixed in & CVE & Plugin & Fixed in \\",
        r"\midrule",
    ]
    for i in range(half):
        a = left[i]
        cells = [cvelink(a["cve"]), slugbreak(a["slug"]),
                 esc(a["patched_version"])]
        if i < len(right):
            b = right[i]
            cells += [cvelink(b["cve"]), slugbreak(b["slug"]),
                      esc(b["patched_version"])]
        else:
            cells += ["", "", ""]
        m.append(" & ".join(cells) + r" \\")
    m += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    open(OUT.replace("FIELD_CVE_TABLE", "FIELD_CVE_MAIN"), "w",
         encoding="utf-8").write("\n".join(m) + "\n")
    print(f"wrote {OUT.replace('FIELD_CVE_TABLE','FIELD_CVE_MAIN')} "
          f"({len(named_recs)} identifiers in two blocks)")
    named = sum(1 for r in recs if r["cve"])
    print(f"wrote {OUT} ({len(recs)} scanned rows, "
          f"{len(d['not_scanned'])} not-scanned notes, {d['cve_published']} published in total)")
    # A count the table cannot enumerate is a claim a reader cannot check, so say so loudly rather
    # than let the table look complete. This is a report, not a failure: the identifiers exist,
    # they were simply never written into the result file.
    # The count and the table have to agree. They did not: the paper claimed 26 published CVEs
    # while the file held 23 identifiers, the other three reports never becoming advisories
    # because those plugins closed support. The claim now equals what the table can list, and
    # this check keeps it that way.
    if named != d["cve_published"]:
        print(f"  the table lists {named} identifiers but cve_published says "
              f"{d['cve_published']}. A count a reader cannot enumerate is not a claim.",
              file=sys.stderr)
        if unrecorded:
            print(f"  scanned record(s) with no identifier: {', '.join(unrecorded)}",
                  file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
