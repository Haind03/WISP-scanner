#!/usr/bin/env python3
"""The external-source (Wordfence-100) table, generated from the contract re-scan.

The shipped table was produced before the harness honoured the contract, so it carries three
defects at once: Progpilot is a column of zeros because an exit-code check discarded every
record on which it exited non-zero while printing valid findings; WISP is scored as though a
non-converged analysis were a clean success; and the run's provenance names an engine commit
that does not exist in the repository.

This regenerates every cell from `wordfence100_contract_v3.json` with record-clustered
bootstrap intervals, and writes both the LaTeX table body the manuscript inputs and a JSON so
the numbers can be checked without LaTeX.

    python3 -m eval.external_table_v3
"""
from __future__ import annotations
import os, sys, json, argparse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
SYS_ROOT = os.path.dirname(ROOT)

PV = os.path.join(SYS_ROOT, "revision-cns-v2", "progpilot_v3")
OUTD = os.path.join(SYS_ROOT, "revision-cns-v2", "out")
LATEX = os.path.join(SYS_ROOT, "2026-07-07", "latex")

# Both record-level per-dataset tables are the same shape and the same failure policy, so they
# are generated by the same code from the same scanner output. Two generators is how two tables
# come to disagree about the same tool.
DATASETS = {
    "wordfence": (os.path.join(PV, "wordfence100_contract_v3.json"),
                  os.path.join(OUTD, "EXTERNAL_TABLE_V3.json"),
                  os.path.join(LATEX, "EXTERNAL_TABLE.tex")),
    "testset325": (os.path.join(PV, "testset325_contract_v3.json"),
                   os.path.join(OUTD, "TESTSET325_TABLE_V3.json"),
                   os.path.join(LATEX, "TESTSET325_TABLE.tex")),
}

TOOLS = [("wisp", "\\textbf{WISP}"), ("wpt", "wp-taint-scan"),
         ("semgrep", "Semgrep"), ("progpilot", "Progpilot")]
REPS, SEED = 10000, 20260730


def boot(vals, reps=REPS, seed=SEED):
    """Record bootstrap. One record per plugin on this set, so record and cluster coincide."""
    import numpy as np
    n = len(vals)
    if not n:
        return 0.0, 0.0, 0.0
    a = np.asarray(vals, dtype=float)
    rng = np.random.default_rng(seed)
    draws = rng.choice(a, size=(reps, n), replace=True).mean(axis=1)
    lo, hi = (float(x) for x in np.percentile(draws, [2.5, 97.5]))
    return round(float(a.mean()), 4), round(lo, 4), round(hi, 4)




def ladder_table(ladder_json, out_tex):
    """The supplement's class-free external ladder, generated with the rungs named correctly.

    The published table had columns `hunk@1` and `hunk@10` for what its own caption described as
    "automatic line overlap within five lines of a changed line". Contract s2 is explicit that
    proximity@5 and same-hunk are different sets and keep different names, and the table had no
    exact-changed-line column at all. All three rungs are separate here.
    """
    d = json.load(open(ladder_json))
    fr = d["first_rank_per_record"]
    n = len(d["record_keys"])
    rungs = [("in_patched_file", "file"), ("same_callable_as_change", "callable"),
             ("on_exact_changed_line", "exact"), ("within_5_changed_lines", "prox@5"),
             ("same_diff_hunk", "hunk")]
    cols = [(r, lab, K) for r, lab in rungs for K in (1, 10)]

    def ind(t, r, K):
        return [1 if (x is not None and x <= K) else 0 for x in fr[t][r]]

    lines = ["% Auto-generated by eval/external_table_v3.py:ladder_table from",
             "% WORDFENCE_LADDER_TRUE_V3.json. Do not edit by hand."]
    for t, disp in TOOLS:
        vals, cis = [], []
        for r, _, K in cols:
            pt, lo, hi = boot(ind(t, r, K))
            vals.append(("\\textbf{%.2f}" % pt) if t == "wisp" else ("%.2f" % pt))
            cis.append("{\\scriptsize[%.2f,\\,%.2f]}" % (lo, hi))
        lines.append("%s & %s \\\\" % (disp, " & ".join(vals)))
        lines.append("& %s \\\\[1pt]" % " & ".join(cis))
    lines.append(r"\bottomrule")
    with open(out_tex, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", out_tex, "(%d records, %d rung columns)" % (n, len(cols)))
    return out_tex




def perclass_fragment(scan, out_tex):
    """The per-class emission sentence, generated. Every one of its figures moved when the
    contract failure policy was applied (auth 23/27 -> 20/27, deserial 4/4 -> 3/4, and so on),
    which is exactly why a hand-written list of nine fractions does not belong in a paper."""
    import collections
    det = json.load(open(scan))["details"]
    by = collections.defaultdict(lambda: [0, 0])
    for r in det:
        w = r.get("wisp") or {}
        by[r.get("cls") or "other"][1] += 1
        if w.get("hit") and not w.get("err"):
            by[r.get("cls") or "other"][0] += 1
    items = sorted(by.items(), key=lambda kv: (-kv[1][0] / kv[1][1], -kv[1][1]))
    parts = ["%s %d/%d (%.2f)" % (c, h, n, h / n) for c, (h, n) in items]
    body = ("% Auto-generated by eval/external_table_v3.py:perclass_fragment. "
            "Do not edit by hand.\n" + ", ".join(parts[:-1]) + ", and " + parts[-1] + ".\n")
    with open(out_tex, "w", encoding="utf-8") as fh:
        fh.write(body)
    print("wrote", out_tex)
    return out_tex


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default="all", choices=["all"] + sorted(DATASETS))
    a = ap.parse_args()
    names = sorted(DATASETS) if a.dataset == "all" else [a.dataset]
    for nm in names:
        scan, oj, ot = DATASETS[nm]
        if not os.path.isfile(scan):
            print(f"[{nm}] SKIP: {os.path.relpath(scan, SYS_ROOT)} not present")
            continue
        print(f"=== {nm} ===")
        one(scan, oj, ot)
        if nm == "wordfence":
            lj = os.path.join(OUTD, "WORDFENCE_LADDER_TRUE_V3.json")
            if os.path.isfile(lj):
                ladder_table(lj, os.path.join(LATEX, "EXTERNAL_LADDER_TABLE.tex"))
            perclass_fragment(scan, os.path.join(LATEX, "EXTERNAL_PERCLASS.tex"))


def one(scan, out_json, out_tex):
    class _A: pass
    a = _A(); a.scan = scan; a.out_json = out_json; a.out_tex = out_tex

    d = json.load(open(a.scan))
    det, summ, prov = d["details"], d["summary"], d["provenance"]
    n = len(det)

    rows = [("class emission", lambda r, t: r[t]["hit"]),
            ("patch-file@1", lambda r, t: r[t]["pf"]["1"]),
            ("patch-file@10", lambda r, t: r[t]["pf"]["10"]),
            ("class-and-file@1", lambda r, t: r[t]["cf"]["1"]),
            ("class-and-file@10", lambda r, t: r[t]["cf"]["10"])]

    res = {
        "schema_version": "external-table-v3",
        "dataset": os.path.basename(a.scan).replace("_contract_v3.json", ""),
        "n_records": n,
        "source": os.path.relpath(a.scan, SYS_ROOT),
        "bootstrap": {"reps": REPS, "seed": SEED, "unit": "record (one per plugin)"},
        "provenance": {"wisp_config": prov.get("wisp_config"),
                       "git_dirty": prov.get("git_dirty"),
                       "failure_rule": prov.get("failure_rule"),
                       "ground_truth_module": prov.get("ground_truth_module"),
                       "timeouts_seconds": prov.get("timeouts_seconds")},
        "cells": {}, "coverage": {}, "findings_per_plugin": {}, "errors": {},
    }
    for tool, _ in TOOLS:
        res["cells"][tool] = {}
        for label, get in rows:
            res["cells"][tool][label] = dict(zip(
                ("rate", "lo", "hi"), boot([get(r, tool) for r in det])))
        res["coverage"][tool] = summ[tool]["coverage"]
        res["findings_per_plugin"][tool] = summ[tool]["findings_per_plugin"]
        res["errors"][tool] = summ[tool].get("errors_by_kind", {})
    res["wisp_non_converged"] = summ["wisp"].get("non_converged")

    lines = ["%% Auto-generated by eval/external_table_v3.py from %s."
             % os.path.basename(a.scan),
             "% Every cell is a JSON pointer, not a transcription. Do not edit by hand."]
    for label, _ in rows:
        vals = " & ".join("%s%.3f%s" % ("\\textbf{" if t == "wisp" else "",
                                        res["cells"][t][label]["rate"],
                                        "}" if t == "wisp" else "") for t, _ in TOOLS)
        cis = " & ".join("{\\scriptsize[%.2f,\\,%.2f]}" % (res["cells"][t][label]["lo"],
                                                          res["cells"][t][label]["hi"])
                         for t, _ in TOOLS)
        lines.append("%-18s & %s \\\\" % (label, vals))
        lines.append("& %s \\\\[1pt]" % cis)
    lines.append("completed          & " + " & ".join(
        "%s%.2f%s" % ("\\textbf{" if t == "wisp" else "", res["coverage"][t],
                      "}" if t == "wisp" else "") for t, _ in TOOLS) + " \\\\")
    lines.append("findings/plugin    & " + " & ".join(
        "%.1f" % res["findings_per_plugin"][t] for t, _ in TOOLS) + " \\\\")
    lines.append(r"\bottomrule")

    os.makedirs(os.path.dirname(a.out_json), exist_ok=True)
    json.dump(res, open(a.out_json, "w"), indent=1, sort_keys=True)
    with open(a.out_tex, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"{n} records; WISP non-converged {res['wisp_non_converged']}")
    hdr = f"{'metric':18} " + " ".join(f"{t:>12}" for t, _ in TOOLS)
    print(hdr)
    for label, _ in rows:
        print(f"{label:18} " + " ".join(
            f"{res['cells'][t][label]['rate']:>12.3f}" for t, _ in TOOLS))
    print(f"{'coverage':18} " + " ".join(f"{res['coverage'][t]:>12.2f}" for t, _ in TOOLS))
    print("\nwrote", a.out_json)
    print("wrote", a.out_tex)


if __name__ == "__main__":
    main()
