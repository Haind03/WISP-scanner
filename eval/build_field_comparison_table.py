#!/usr/bin/env python3
"""Generate the four-tool field-comparison table from FIELD_COMPARISON_V1.json.

Every cell is a JSON pointer, not a transcription. Do not edit the .tex by hand.

The table carries three things a reader needs together, because any one of them alone misleads:
the rate under the failure-as-miss policy the whole paper uses, the number of records the tool
never answered, and the ceiling it would reach if every one of those failures were charged as a
hit instead. That last column is what stops the table being read as a capability ordering: two of
the three baselines have ceilings above WISP's measured rate, so their gap is availability and not
localisation, and the caption says so rather than leaving the reader to work it out.

The vocabulary column is the second guard against misreading. A tool with no rule for a class
cannot be said to have looked and missed, so the count of records whose advisory class the tool
cannot express is printed beside its class-rung rate.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYS_ROOT = os.path.dirname(ROOT)
SRC = os.path.join(SYS_ROOT, "revision-cns-v2", "out", "FIELD_COMPARISON_V1.json")
OUT = os.path.join(SYS_ROOT, "2026-07-07", "latex", "FIELD_COMPARISON_TABLE.tex")
DISPLAY = {"wisp": "\\textbf{WISP}", "wpt": "wp-taint-scan",
           "semgrep": "Semgrep", "progpilot": "Progpilot"}
ORDER = ["wisp", "wpt", "semgrep", "progpilot"]


def main():
    d = json.load(open(SRC, encoding="utf-8"))
    n = d["n_records"]
    rows = []
    for t in ORDER:
        v = d["tools"][t]
        c, a = v["counts"], v["aggregate_failure_as_miss"]
        u = v["upper_bound_if_every_failure_were_a_hit"]
        ce = v["class_expressible_ceiling"]
        fails = c["timed_out"] + c["errored"]
        rows.append(
            f"{DISPLAY[t]} & {c['answered']} & {fails} & "
            + " & ".join(f"{a['pf_at_k'][k]:.2f}" for k in ("1", "3", "5", "10"))
            + f" & {u['pf_at_k']['10']:.2f} & "
            + " & ".join(f"{a['cf_at_k'][k]:.2f}" for k in ("1", "10"))
            + f" & {ce['records_class_not_expressible']} \\\\")
    best_pf = max(d["tools"][t]["aggregate_failure_as_miss"]["pf_at_k"]["10"] for t in ORDER)
    best_cf = max(d["tools"][t]["aggregate_failure_as_miss"]["cf_at_k"]["10"] for t in ORDER)
    cap = (
        f"Four scanners on the {n} field-validation records, every one a vulnerability a vendor "
        f"confirmed and fixed. Rates follow the failure-as-miss policy used throughout, so a record "
        f"a tool never answered is a miss over the full denominator of {n}. \\emph{{fail}} counts "
        f"those records. \\emph{{pf@10 ceiling}} is the rate the tool would reach if every one of "
        f"its failures were charged as a hit instead, and it is printed because two ceilings exceed "
        f"WISP's measured rate, so those gaps are availability rather than localization and this "
        f"table is not a capability ordering. \\emph{{no vocab}} counts records whose advisory class "
        f"the tool has no rule for, which is not the same as looking and missing. Budgets are not "
        f"equal here: WISP ran uncapped, Semgrep at 300\\,s and the other two at 60\\,s. The reading "
        f"that survives all of that is the level, not the order: on vulnerabilities known to be "
        f"real, the best patch-file rate any tool reaches is {best_pf:.2f} and the best "
        f"class-and-file rate is {best_cf:.2f}.")
    lines = [
        "% Auto-generated by eval/build_field_comparison_table.py from FIELD_COMPARISON_V1.json.",
        "% Every cell is a JSON pointer, not a transcription. Do not edit by hand.",
        "\\begin{table*}[!t]", "\\centering\\small",
        "\\caption{" + cap + "}", "\\label{tab:s-fieldcmp}",
        "\\setlength{\\tabcolsep}{5pt}",
        "\\begin{tabular}{@{}lcc cccc c cc c@{}}", "\\toprule",
        "& & & \\multicolumn{4}{c}{patch-file success@$K$} & & "
        "\\multicolumn{2}{c}{class-and-file@$K$} & \\\\",
        "\\cmidrule(lr){4-7}\\cmidrule(lr){9-10}",
        "Tool & ans & fail & 1 & 3 & 5 & 10 & pf@10 ceiling & 1 & 10 & no vocab \\\\",
        "\\midrule", *rows, "\\bottomrule", "\\end{tabular}", "\\end{table*}",
    ]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(rows)} tool rows, best pf@10 {best_pf:.2f}, best cf@10 {best_cf:.2f})")


if __name__ == "__main__":
    sys.exit(main())
